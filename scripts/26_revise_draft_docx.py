_id = [9000]

def nid():
    _id[0] += 1
    return str(_id[0])

def el(tag, **attrs):
    e = docx.oxml.OxmlElement(tag)
    for k, v in attrs.items():
        e.set(qn(k), v)
    return e

def mark(tag):
    return el(tag, **{"w:id": nid(), "w:author": AUTHOR, "w:date": DATE})

def make_run(rpr, text, deleted=False):
    r = el("w:r")
    if rpr is not None:
        r.append(copy.deepcopy(rpr))
    t = el("w:delText" if deleted else "w:t")
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    r.append(t)
    return r

def text_runs(p):
    return [r for r in p._p.iter(qn("w:r")) if r.find(qn("w:t")) is not None]

def tracked_replace_run(run, new_text):
    """Replace one run's text by a word-level tracked diff."""
    old = "".join(t.text or "" for t in run.findall(qn("w:t")))   # a run can hold several <w:t> (e.g. around a page-break marker)
    rpr = run.find(qn("w:rPr"))
    a, b = re.findall(r"\S+|\s+", old), re.findall(r"\S+|\s+", new_text)
    parent, idx = run.getparent(), run.getparent().index(run)
    new_nodes = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes():
        if op == "equal":
            new_nodes.append(make_run(rpr, "".join(a[i1:i2])))
        if op in ("delete", "replace"):
            d = mark("w:del"); d.append(make_run(rpr, "".join(a[i1:i2]), deleted=True)); new_nodes.append(d)
        if op in ("insert", "replace"):
            ins = mark("w:ins"); ins.append(make_run(rpr, "".join(b[j1:j2]))); new_nodes.append(ins)
    parent.remove(run)
    for k, n in enumerate(new_nodes):
        parent.insert(idx + k, n)

def replace(p, new_text, run_index=0):
    tracked_replace_run(text_runs(p)[run_index], new_text)

def mark_para(p_el, tag):
    """Mark the paragraph mark itself as inserted/deleted."""
    ppr = p_el.find(qn("w:pPr"))
    if ppr is None:
        ppr = el("w:pPr"); p_el.insert(0, ppr)
    rpr = ppr.find(qn("w:rPr"))
    if rpr is None:
        rpr = el("w:rPr"); ppr.append(rpr)
    rpr.insert(0, mark(tag))

def delete_paragraph(p):
    for r in list(p._p.iter(qn("w:r"))):
        for t in r.findall(qn("w:t")):
            t.tag = qn("w:delText")
        parent = r.getparent(); i = parent.index(r); parent.remove(r)
        d = mark("w:del"); d.append(r); parent.insert(i, d)
    mark_para(p._p, "w:del")

def new_paragraph_after(anchor_el, style_par, parts):
    """parts = [(text, rpr_source_run or None), ...]; returns the new <w:p>."""
    p = el("w:p")
    ppr = style_par._p.find(qn("w:pPr"))
    if ppr is not None:
        ppr = copy.deepcopy(ppr)
        for x in ppr.findall(qn("w:rPr")):
            ppr.remove(x)
        p.append(ppr)
    ins = mark("w:ins")
    for text, src in parts:
        ins.append(make_run(src.find(qn("w:rPr")) if src is not None else None, text))
    p.append(ins)
    mark_para(p, "w:ins")
    anchor_el.addnext(p)
    return p

def image_paragraph_after(anchor_el, image_par, rid, width_in, height_in):
    p = copy.deepcopy(image_par._p)
    for blip in p.iter(qn("a:blip")):
        blip.set(qn("r:embed"), rid)
    emu_w = None
    for ext in p.iter(qn("wp:extent")):
        emu_w = int(ext.get("cx")); ext.set("cy", str(int(emu_w * height_in / width_in)))
    for ext in p.iter(qn("a:ext")):
        if ext.get("cx") is not None:
            ext.set("cy", str(int(int(ext.get("cx")) * height_in / width_in)))
    for dp in p.iter(qn("wp:docPr")):
        dp.set("id", "9901"); dp.set("name", "living_arrangements")
    for r in list(p.iter(qn("w:r"))):
        parent = r.getparent(); i = parent.index(r); parent.remove(r)
        ins = mark("w:ins"); ins.append(r); parent.insert(i, ins)
    mark_para(p, "w:ins")
    anchor_el.addnext(p)
    return p

